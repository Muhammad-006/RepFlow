"""
Writes client/build_config.py with this laptop's current LAN IP address(es).

The phone app tries these first when it starts, which makes the first
connection instant. It is only a head start: if the laptop's IP changes
later (different Wi-Fi, hotspot...), the app still finds it automatically
through network discovery. Run by BUILD_APK.bat / build_apk.sh.
"""
import os
import socket


def lan_ips():
    ips = set()
    try:
        for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
            ips.add(info[4][0])
    except OSError:
        pass
    for probe in ("8.8.8.8", "192.168.1.1", "10.255.255.255"):
        try:
            s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            s.connect((probe, 80))
            ips.add(s.getsockname()[0])
            s.close()
        except OSError:
            pass

    def private(ip):
        a, b = (int(x) for x in ip.split(".")[:2])
        return a == 10 or (a == 172 and 16 <= b <= 31) or (a == 192 and b == 168)

    return sorted(ip for ip in ips if private(ip))


if __name__ == "__main__":
    ips = lan_ips()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "client", "build_config.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write('"""Generated by tools/write_build_config.py at APK build time -- safe to delete."""\n')
        f.write(f"BAKED_HOSTS = {ips!r}\n")
    print(f"[RepFlow] Baked laptop address(es) into the app: {', '.join(ips) or '(none found - discovery will handle it)'}")
